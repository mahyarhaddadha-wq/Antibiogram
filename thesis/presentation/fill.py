P_RE = re.compile(r"<a:p>(?:(?!</a:p>).)*</a:p>|<a:p/>", re.S)
R_RE = re.compile(r"<a:r>(?:(?!</a:r>).)*</a:r>", re.S)


def set_rtl(par):
    """Mark the paragraph right to left, keeping any alignment it already has."""
    m = re.search(r"<a:pPr\b([^>]*?)(/?)>", par)
    if not m:
        return par.replace("<a:p>", '<a:p><a:pPr rtl="1" algn="r"/>', 1)
    attrs, close = m.group(1), m.group(2)
    if "rtl=" not in attrs:
        attrs += ' rtl="1"'
    if "algn=" not in attrs:
        attrs += ' algn="r"'
    return par[:m.start()] + f"<a:pPr{attrs}{close}>" + par[m.end():]


def set_text(par, text):
    """Collapse the paragraph to one run carrying the new text."""
    runs = R_RE.findall(par)
    if not runs:
        return par
    first = runs[0]
    new = re.sub(r"<a:t>.*?</a:t>",
                 "<a:t>" + html.escape(text, quote=False) + "</a:t>",
                 first, count=1, flags=re.S)
    out = par.replace(first, new, 1)
    for extra in runs[1:]:
        out = out.replace(extra, "", 1)
    return out


def convert(name, page):
    path = f"unpacked/ppt/slides/{name}.xml"
    x = open(path, encoding="utf8").read()
    pars = P_RE.findall(x)
    want = C[name]
    if len(pars) != len(want):
        sys.exit(f"{name}: template has {len(pars)} paragraphs, content has {len(want)}")

    for par, text in zip(pars, want):
        new = set_rtl(par)
        if text is not None:
            new = set_text(new, text)
        elif page is not None:                    # the slide-number placeholder
            new = set_text(new, page)
        x = x.replace(par, new, 1)

    # The thesis fonts: Cambria is the template's display face, Calibri its
    # body face, so the two map onto IRTitr and IRNazanin.
    x = x.replace('<a:cs typeface="Cambria"', '<a:cs typeface="IRTitr"')
    x = x.replace('<a:cs typeface="Calibri"', '<a:cs typeface="IRNazanin"')
    x = x.replace('<a:cs typeface="Arial"', '<a:cs typeface="IRNazanin"')
    open(path, "w", encoding="utf8").write(x)
    print(f"  {name:9} {len(pars):>2} paragraphs -> page {page or '—'}")


for name, page in DECK:
    convert(name, page)

